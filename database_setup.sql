create table if not exists public.teams (
    id text primary key,
    name text not null unique,
    short_name text not null,
    color text not null default '#ffd900',
    seed integer not null unique
);

create table if not exists public.matches (
    id text primary key,
    match_number integer not null unique check (match_number between 1 and 10),
    team1_id text not null references public.teams(id),
    team2_id text not null references public.teams(id),
    start_time time not null,
    end_time time not null,
    overs integer not null default 6 check (overs = 6),
    status text not null default 'Scheduled' check (status in ('Scheduled', 'Live', 'Completed')),
    team1_score text,
    team2_score text,
    batting_team_id text references public.teams(id),
    balls_completed integer not null default 0 check (balls_completed between 0 and 36),
    winner_team_id text references public.teams(id),
    is_tie boolean not null default false,
    result_note text,
    constraint different_teams check (team1_id <> team2_id),
    constraint winner_is_participant check (winner_team_id is null or winner_team_id = team1_id or winner_team_id = team2_id)
);

-- Add live innings tracking to existing projects as well as fresh installs.
alter table public.matches
    add column if not exists batting_team_id text references public.teams(id);
alter table public.matches
    add column if not exists balls_completed integer not null default 0
    check (balls_completed between 0 and 36);

create table if not exists public.players (
    id bigint generated by default as identity primary key,
    team_id text not null references public.teams(id) on delete cascade,
    roster_number integer not null,
    name text not null,
    role text not null default 'Player',
    jersey_number text,
    profile_details text,
    photo_path text,
    constraint unique_team_roster_number unique (team_id, roster_number)
);

alter table public.players add column if not exists profile_details text;
alter table public.players add column if not exists photo_path text;

create table if not exists public.batting_scores (
    id bigint generated by default as identity primary key,
    match_id text not null references public.matches(id) on delete cascade,
    team_id text not null references public.teams(id) on delete cascade,
    player_id bigint references public.players(id) on delete set null,
    player_name text not null,
    batting_order integer not null,
    runs integer not null default 0 check (runs >= 0),
    balls_faced integer not null default 0 check (balls_faced >= 0),
    fours integer not null default 0 check (fours >= 0),
    sixes integer not null default 0 check (sixes >= 0),
    dismissal text not null default 'Not out',
    constraint unique_match_batter unique (match_id, team_id, player_id),
    constraint boundaries_within_score check (4 * fours + 6 * sixes <= runs),
    constraint boundaries_within_balls check (fours + sixes <= balls_faced)
);

create table if not exists public.bowling_figures (
    id bigint generated by default as identity primary key,
    match_id text not null references public.matches(id) on delete cascade,
    team_id text not null references public.teams(id) on delete cascade,
    player_id bigint references public.players(id) on delete set null,
    player_name text not null,
    bowling_order integer not null,
    balls_bowled integer not null default 0 check (balls_bowled >= 0),
    maidens integer not null default 0 check (maidens >= 0),
    runs_conceded integer not null default 0 check (runs_conceded >= 0),
    wickets integer not null default 0 check (wickets between 0 and 10),
    constraint unique_match_bowler unique (match_id, team_id, player_id),
    constraint maidens_within_overs check (maidens <= balls_bowled / 6)
);

